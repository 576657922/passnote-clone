for (const e of exams) insExam.run(e.code, e.name, e.name_ja, e.subtitle, e.badge, e.sort)

const insSession = db.prepare('INSERT INTO exam_sessions (code, exam_code, label, year, season, sort) VALUES (?, ?, ?, ?, ?, ?)')
for (const s of sessions) insSession.run(s.code, s.exam, s.label, s.year, s.season, s.sort)

const insTerm = db.prepare('INSERT INTO terms (slug, title, title_zh, category, description) VALUES (?, ?, ?, ?, ?)')
const termIds = {}
for (const t of terms) {
  const r = insTerm.run(t.slug, t.title, t.title_zh, t.category, t.description)
  termIds[t.slug] = Number(r.lastInsertRowid)
}

const insQ = db.prepare('INSERT INTO questions (exam_code, session_code, number, domain, text, choices, answer, explanation, explanation_zh, is_trial) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)')
const insTQ = db.prepare('INSERT INTO term_questions (term_id, question_id) VALUES (?, ?)')
const sessionExam = Object.fromEntries(sessions.map(s => [s.code, s.exam]))
for (const q of questions) {
  const r = insQ.run(sessionExam[q.s], q.s, q.n, q.d, q.t, JSON.stringify(q.c), q.a, q.e, q.ez, q.trial ? 1 : 0)
  const qid = Number(r.lastInsertRowid)
  for (const slug of q.tm || []) {
    if (termIds[slug]) insTQ.run(termIds[slug], qid)
  }
}

